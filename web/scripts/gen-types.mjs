// Generate TypeScript types for the demo snapshot from its JSON Schema.
//
// The schema (demo/snapshot.schema.json) is exported from the Pydantic models by
// `knowledge demo export`, so Python stays the single source of truth. Run with
// `--check` in CI to fail when the committed types drift from the schema.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const schemaPath = resolve(here, "../../demo/snapshot.schema.json");
const outputPath = resolve(here, "../src/types/snapshot.gen.ts");

const banner = `/* Generated by \`pnpm gen:types\` from demo/snapshot.schema.json. Do not edit by hand. */`;

const schema = JSON.parse(await readFile(schemaPath, "utf8"));
// The $id is a documentation URL, not something to resolve while compiling.
delete schema.$id;

const generated = await compile(schema, "LibrarySnapshot", {
  bannerComment: banner,
  additionalProperties: false,
  strictIndexSignatures: true,
  style: { singleQuote: false, semi: true, printWidth: 100 },
});

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== generated) {
    console.error("src/types/snapshot.gen.ts is out of date; run `pnpm gen:types`.");
    process.exit(1);
  }
  console.log("Snapshot types are up to date.");
} else {
  await writeFile(outputPath, generated);
  console.log(`Wrote ${outputPath}`);
}

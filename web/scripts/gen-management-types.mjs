// Generate TypeScript types for the B1 management API from the exported schema.
//
// The schema is exported from the Python DTO/query models by
// `python scripts/export_management_schema.py`, so Python remains the single
// source of truth. Run with `--check` to fail when the committed types drift.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const schemaPath = resolve(here, "../src/management/schema.json");
const outputPath = resolve(here, "../src/management/types.gen.ts");

const banner =
  "/* Generated by `node web/scripts/gen-management-types.mjs` from web/src/management/schema.json. Do not edit by hand. */";

const schema = JSON.parse(await readFile(schemaPath, "utf8"));
delete schema.$id;

const definitionNames = Object.keys(schema.$defs ?? {});
const schemaForTypes = {
  ...schema,
  properties: Object.fromEntries(
    definitionNames.map((name) => [name, { $ref: `#/$defs/${name}` }]),
  ),
  required: definitionNames,
};

const generated = await compile(schemaForTypes, "ManagementApiSchemaBundle", {
  bannerComment: banner,
  additionalProperties: false,
  strictIndexSignatures: true,
  style: { singleQuote: false, semi: true, printWidth: 100 },
});

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== generated) {
    console.error(
      "web/src/management/types.gen.ts is out of date; run `node web/scripts/gen-management-types.mjs`.",
    );
    process.exit(1);
  }
  console.log("Management types are up to date.");
} else {
  await writeFile(outputPath, generated);
  console.log(`Wrote ${outputPath}`);
}
